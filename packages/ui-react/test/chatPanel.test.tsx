// @vitest-environment jsdom
import { act, cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, describe, expect, it, vi } from "vitest";

import { FadenstackClient, SDK_VERSION, loginWithPassword } from "@fadenstack/client";
import { FadenstackAgent, MemorySessionStore, defineTool } from "@fadenstack/agents";
import {
  AgentChatViewModel, ApprovalBroker, MemoryClipboard, MemoryPreferenceStore, immediateScheduler, majorMinor, type AgentChatOptions,
} from "@fadenstack/ui";
import { ChatPanel, type ChatPanelProps } from "@fadenstack/ui-react";
import { FakeGateway, lastToolResults, type FakeModel } from "@fadenstack/testing";

afterEach(cleanup);

async function panel(model: FakeModel, risk: "write" | "destructive" = "write", options: AgentChatOptions = {}, panelProps: Partial<ChatPanelProps> = {}) {
  const gateway = new FakeGateway({
    agents: [{
      slug: "page", name: "Page assistant", ui: { greeting: "I read the page you are on.", suggestions: ["Summarise this page"] },
      contract: [{ name: "fill_field", risk }],
    }],
    model,
  });
  const { client, tokens } = FadenstackClient.forAgent({ serverUrl: gateway.serverUrl, agent: "page", fetch: gateway.fetch });
  await tokens.signIn(await loginWithPassword({ apiUrl: gateway.serverUrl, email: "user@example.com", password: "secret", fetch: gateway.fetch }));
  const filled: string[] = [];
  const approvals = new ApprovalBroker();
  const agent = FadenstackAgent.createBuilder()
    .useClient(client)
    .useSessionStore(new MemorySessionStore())
    .useApprovals(approvals)
    .addTools(defineTool<{ value: string }>({
      name: "fill_field", toolClass: "write",
      parameters: { type: "object", properties: { value: { type: "string" } }, required: ["value"] },
      describe: () => 'textbox "Name" on example.com',
      run: ({ value }) => {
        filled.push(value);
        return "filled";
      },
    }))
    .build();
  const clipboard = new MemoryClipboard();
  const chat = new AgentChatViewModel(agent, approvals, { scheduler: immediateScheduler, clipboard, preferences: new MemoryPreferenceStore(), ...options });
  await act(() => chat.initialize());
  render(<ChatPanel chat={chat} {...panelProps} />);
  return { chat, filled, clipboard };
}

describe("ChatPanel", () => {
  it("shows the agent's greeting and suggestions, and follows the browser's theme", async () => {
    await panel(() => ({ text: "ok" }));
    expect(screen.getByText("Page assistant")).toBeTruthy();
    expect(screen.getByText("I read the page you are on.")).toBeTruthy();
    expect(screen.getByRole("button", { name: "Summarise this page" })).toBeTruthy();
    expect(document.querySelector(".fdn-chat")!.getAttribute("data-theme")).toBe("system");
    expect(document.querySelector(".fdn-empty-mark .fdn-agent-avatar")).toBeTruthy();
    expect(document.querySelector(".fdn-composer + .fdn-ai-notice > span[dir=auto]")!.textContent).toBe("Answers are generated by AI and can be wrong. Check what matters.");
  });

  it("leaves the AI notice out only when the host empties it; the Fadenstack link then stands alone", async () => {
    await panel(() => ({ text: "ok" }), "write", { strings: { aiNotice: "" } });
    expect(document.querySelector(".fdn-ai-notice")!.textContent).toBe("Fadenstack");
    expect(document.querySelector(".fdn-ai-notice-separator")).toBeNull();
    cleanup();
    await panel(() => ({ text: "ok" }), "write", { strings: { aiNotice: "" }, branding: false });
    expect(document.querySelector(".fdn-ai-notice")).toBeNull();
  });

  it("sends with Enter and renders the answer as Markdown, never as HTML", async () => {
    await panel(() => ({ text: "**Bold** and <b>not bold</b>\n\n```js\nlet x = 1;\n```" }));
    const box = screen.getByRole("textbox");
    fireEvent.change(box, { target: { value: "Hello" } });
    await act(async () => {
      fireEvent.keyDown(box, { key: "Enter" });
    });
    await waitFor(() => expect(screen.getByText("Bold").tagName).toBe("STRONG"));
    expect(screen.getByText("Hello")).toBeTruthy();
    expect(document.querySelector(".fdn-md b")).toBeNull();
    expect(screen.getByText("let x = 1;").tagName).toBe("CODE");
    expect(screen.getByRole("button", { name: "Copy code" })).toBeTruthy();
  });

  it("copies a table of an answer for a spreadsheet", async () => {
    const { clipboard } = await panel(() => ({ text: "| Task | Interval |\n|---|---|\n| Seal check | 2 000 h |" }));
    fireEvent.change(screen.getByRole("textbox"), { target: { value: "Intervals?" } });
    await act(async () => {
      fireEvent.click(screen.getByRole("button", { name: "Send" }));
    });
    fireEvent.click(await screen.findByRole("button", { name: "Copy table" }));
    expect(clipboard.lastText).toBe("Task\tInterval\nSeal check\t2 000 h");
    expect(clipboard.lastHtml).toContain("<td>Seal check</td>");
  });

  it("asks with a card and runs the tool when Allow is clicked", async () => {
    const { filled } = await panel((r) => (lastToolResults(r).size ? { text: "Filled in." }
      : { toolCalls: [{ name: "fill_field", arguments: { value: "Jane" } }] }));
    fireEvent.change(screen.getByRole("textbox"), { target: { value: "Fill my name" } });
    await act(async () => {
      fireEvent.click(screen.getByRole("button", { name: "Send" }));
    });
    const allow = await screen.findByRole("button", { name: "Allow" });
    expect(screen.getByText("Run fill_field?")).toBeTruthy();
    expect(screen.getByText('textbox "Name" on example.com').className).toBe("fdn-approval-target");
    expect(screen.getByText("value: Jane")).toBeTruthy();
    await act(async () => {
      fireEvent.click(allow);
    });
    await waitFor(() => expect(screen.getByText("Filled in.")).toBeTruthy());
    expect(filled).toEqual(["Jane"]);
    expect(screen.getByText("Allowed")).toBeTruthy();
    expect(screen.getByText("Ran fill_field")).toBeTruthy();
  });

  it("lets the user pick a tool mode", async () => {
    const { chat } = await panel(() => ({ text: "ok" }));
    fireEvent.click(screen.getByRole("button", { name: /Tool mode/ }));
    await act(async () => {
      fireEvent.click(screen.getByRole("menuitemradio", { name: /Read only/ }));
    });
    expect(chat.toolMode).toBe("read_only");
  });

  it("offers Allow for this chat and Allow always for a tool that changes something", async () => {
    await panel((r) => (lastToolResults(r).size ? { text: "Filled in." } : { toolCalls: [{ name: "fill_field", arguments: { value: "Jane" } }] }));
    fireEvent.change(screen.getByRole("textbox"), { target: { value: "Fill my name" } });
    await act(async () => {
      fireEvent.click(screen.getByRole("button", { name: "Send" }));
    });
    expect(await screen.findByRole("button", { name: "Allow for this chat" })).toBeTruthy();
    const always = screen.getByRole("button", { name: "Allow always" });
    await act(async () => {
      fireEvent.click(always);
    });
    await waitFor(() => expect(screen.getByText("Allowed always")).toBeTruthy());
  });

  it("offers only Allow and Deny for a tool that cannot be undone", async () => {
    await panel((r) => (lastToolResults(r).size ? { text: "Sent." } : { toolCalls: [{ name: "fill_field", arguments: { value: "Jane" } }] }), "destructive");
    fireEvent.change(screen.getByRole("textbox"), { target: { value: "Send it" } });
    await act(async () => {
      fireEvent.click(screen.getByRole("button", { name: "Send" }));
    });
    expect(await screen.findByRole("button", { name: "Allow" })).toBeTruthy();
    expect(screen.getByRole("button", { name: "Deny" })).toBeTruthy();
    expect(screen.queryByRole("button", { name: "Allow for this chat" })).toBeNull();
    expect(screen.queryByRole("button", { name: "Allow always" })).toBeNull();
    await act(async () => {
      fireEvent.click(screen.getByRole("button", { name: "Deny" }));
    });
  });

  it("resets approvals from the tool-mode menu", async () => {
    const { chat } = await panel(() => ({ text: "ok" }));
    fireEvent.click(screen.getByRole("button", { name: /Tool mode/ }));
    await act(async () => {
      fireEvent.click(screen.getByRole("menuitem", { name: "Reset approvals" }));
    });
    expect(chat.isModeMenuOpen).toBe(false);
  });
});

describe("ChatPanel's settings", () => {
  it("lets the user pick a language, and the whole panel speaks it", async () => {
    await panel(() => ({ text: "ok" }), "write", { automaticLanguage: "en-US" }, { settingsExtra: <button type="button">Sign out</button> });
    fireEvent.click(screen.getByRole("button", { name: "Settings" }));
    expect(screen.getAllByRole("menuitemradio").map((b) => b.textContent)).toEqual(
      ["Automatic (English)", "English", "Deutsch", "Français", "Español", "中文（简体）"]);
    expect(screen.getByRole("button", { name: "Sign out" })).toBeTruthy();
    await act(async () => {
      fireEvent.click(screen.getByRole("menuitemradio", { name: "Deutsch" }));
    });
    expect(screen.queryByRole("menu")).toBeNull();
    expect(screen.getByRole("textbox").getAttribute("placeholder")).toBe("Stellen Sie eine Frage");
    expect(screen.getByRole("button", { name: "Einstellungen" })).toBeTruthy();
    expect(document.querySelector(".fdn-chat")!.getAttribute("lang")).toBe("de");
  });

  it("shows the language the organisation fixed, without a choice", async () => {
    await panel(() => ({ text: "ok" }), "write", { lockedLanguage: "fr" });
    fireEvent.click(screen.getByRole("button", { name: "Paramètres" }));
    expect(screen.getByText("Défini par votre organisation")).toBeTruthy();
    expect(screen.getAllByRole("menuitemradio").every((b) => (b as HTMLButtonElement).disabled)).toBe(true);
  });

  it("always has the settings button, with About as its last item", async () => {
    await panel(() => ({ text: "ok" }), "write", { strings: { send: "Go" } });
    fireEvent.click(screen.getByRole("button", { name: "Settings" }));
    expect(screen.queryAllByRole("menuitemradio")).toEqual([]);
    expect(screen.getAllByRole("menuitem").map((b) => b.textContent)).toEqual(["About"]);
    cleanup();
    await panel(() => ({ text: "ok" }), "write", {}, { settingsExtra: <button type="button" role="menuitem">Sign out</button> });
    fireEvent.click(screen.getByRole("button", { name: "Settings" }));
    expect(screen.getAllByRole("menuitem").map((b) => b.textContent)).toEqual(["Sign out", "About"]);
  });
});

const sdkMinor = majorMinor(SDK_VERSION)!;

describe("ChatPanel's About and links", () => {
  it("has a muted Fadenstack link after the AI notice, which opens through openLink", async () => {
    const opened: string[] = [];
    await panel(() => ({ text: "ok" }), "write", { openLink: (url) => opened.push(url), refSource: "office" });
    const link = screen.getByRole("link", { name: "Fadenstack (opens in a new tab)" }) as HTMLAnchorElement;
    expect(link.closest(".fdn-ai-notice")).toBeTruthy();
    expect(link.getAttribute("href")).toBe(`https://fadenstack.com/?ref=office-panel&v=${sdkMinor}`);
    expect(link.getAttribute("target")).toBe("_blank");
    expect(link.getAttribute("rel")).toBe("noopener noreferrer");
    expect(link.querySelector("svg")!.getAttribute("aria-hidden")).toBe("true");
    expect(fireEvent.click(link)).toBe(false); // the browser does not follow it: the host opens it
    expect(opened).toEqual([link.getAttribute("href")]);
  });

  it("opens links in a new tab without a way back by default", async () => {
    const open = vi.spyOn(window, "open").mockReturnValue(null);
    try {
      await panel(() => ({ text: "ok" }));
      fireEvent.click(screen.getByRole("link", { name: /^Fadenstack/ }));
      expect(open).toHaveBeenCalledWith(`https://fadenstack.com/?ref=sdk-panel&v=${sdkMinor}`, "_blank", "noopener,noreferrer");
    } finally {
      open.mockRestore();
    }
  });

  it("shows About over the panel: the agent, the SDK, the server and links; Escape closes it and the gear has the focus", async () => {
    const opened: string[] = [];
    await panel(() => ({ text: "ok" }), "write", { openLink: (url) => opened.push(url) });
    fireEvent.click(screen.getByRole("button", { name: "Settings" }));
    fireEvent.click(screen.getByRole("menuitem", { name: "About" }));
    expect(screen.queryByRole("menu")).toBeNull();
    const about = screen.getByRole("dialog", { name: "About" });
    expect(document.activeElement).toBe(screen.getByRole("button", { name: "Close" }));
    expect(about.querySelector(".fdn-about-name")!.textContent).toBe("Page assistant");
    expect([...about.querySelectorAll(".fdn-about-line")].map((l) => l.textContent)).toEqual([
      "Version 1", "Model: fake-model", `Fadenstack SDK ${SDK_VERSION} (TypeScript)`, "Server: https://faden.test",
    ]);
    const links = [...about.querySelectorAll("a")];
    expect(links.map((a) => [a.getAttribute("aria-label"), a.getAttribute("href"), a.getAttribute("target"), a.getAttribute("rel")])).toEqual([
      ["Help (opens in a new tab)", "https://faden.test/help/", "_blank", "noopener noreferrer"],
      ["Fadenstack (opens in a new tab)", `https://fadenstack.com/?ref=sdk-about&v=${sdkMinor}`, "_blank", "noopener noreferrer"],
      ["Developer docs (opens in a new tab)", `https://developers.fadenstack.com/?ref=sdk-about&v=${sdkMinor}`, "_blank", "noopener noreferrer"],
    ]);
    fireEvent.click(links[2]!);
    expect(opened).toEqual([`https://developers.fadenstack.com/?ref=sdk-about&v=${sdkMinor}`]);
    fireEvent.keyDown(screen.getByRole("button", { name: "Close" }), { key: "Escape" });
    expect(screen.queryByRole("dialog")).toBeNull();
    expect(document.activeElement).toBe(screen.getByRole("button", { name: "Settings" }));
  });

  it("closes About with its button and with a press outside; copies the details", async () => {
    const { chat, clipboard } = await panel(() => ({ text: "ok" }));
    act(() => chat.setAboutOpen(true));
    await act(async () => {
      fireEvent.click(screen.getByRole("button", { name: "Copy details" }));
    });
    expect(clipboard.lastText).toBe(["Page assistant", "Version 1", "Model: fake-model", `Fadenstack SDK ${SDK_VERSION} (TypeScript)`,
      "Server: https://faden.test"].join("\n"));
    expect(screen.getByRole("button", { name: "Copied" })).toBeTruthy();
    fireEvent.click(screen.getByRole("button", { name: "Close" }));
    expect(chat.isAboutOpen).toBe(false);
    act(() => chat.setAboutOpen(true));
    fireEvent.pointerDown(screen.getByRole("textbox"));
    expect(screen.queryByRole("dialog")).toBeNull();
  });

  it("keeps About when branding is false; only the footer link goes", async () => {
    await panel(() => ({ text: "ok" }), "write", { branding: false });
    expect(screen.queryByRole("link", { name: /^Fadenstack/ })).toBeNull();
    expect(document.querySelector(".fdn-ai-notice")!.textContent).toBe("Answers are generated by AI and can be wrong. Check what matters.");
    fireEvent.click(screen.getByRole("button", { name: "Settings" }));
    fireEvent.click(screen.getByRole("menuitem", { name: "About" }));
    expect(screen.getByRole("dialog", { name: "About" }).querySelectorAll("a")).toHaveLength(3);
  });

  it("speaks the panel's language, the brand name aside", async () => {
    await panel(() => ({ text: "ok" }), "write", { lockedLanguage: "de" });
    fireEvent.click(screen.getByRole("button", { name: "Einstellungen" }));
    fireEvent.click(screen.getByRole("menuitem", { name: "Über" }));
    const about = screen.getByRole("dialog", { name: "Über" });
    expect([...about.querySelectorAll("a")].map((a) => a.getAttribute("aria-label"))).toEqual([
      "Hilfe (öffnet in einem neuen Tab)", "Fadenstack (öffnet in einem neuen Tab)", "Entwicklerdokumentation (öffnet in einem neuen Tab)",
    ]);
    expect(screen.getByRole("button", { name: "Details kopieren" })).toBeTruthy();
  });
});
